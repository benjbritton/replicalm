"""Where things live, resolved from the environment rather than hardcoded.

WHY
---
The benchmark scripts were written against one machine and carried its drive
letters -- 1,260 absolute paths across 86 files, including a JSON inventory of
453 tiles rooted at `D:\\`. That makes the harness unrunnable by anyone else,
which defeats the point of publishing it: the claims in `docs/` rest on these
scripts, and a reader who cannot run them cannot check the claims.

CONFIGURATION
-------------
Two environment variables, both optional:

    REPLICALM_ROOT   the repository. Defaults to the parent of this file's
                     directory, which is correct for a normal clone, so it
                     rarely needs setting.
    REPLICALM_DATA   where the G-LiHT products live. Defaults to `D:\\` on
                     Windows and `/data` elsewhere.

Under `REPLICALM_DATA` the harness expects the layout the products ship with:

    <data>/_Archive_EdgeFixed/<Region>/<Sub>/<Sub>/*_DEM_0p5m_v1.tif
    <data>/GLiHT_LAS_orig/<Region>/<Sub>/<Sub>/*.las

Either root can be overridden directly with `REPLICALM_DEM_ROOT` and
`REPLICALM_LAS_ROOT` if the products are somewhere else entirely.

The data itself is not redistributed. It is NASA G-LiHT from the AMIGACarb and
Yucatan campaigns; `benchmarks/results/` records which tiles were used and how
each sample window was chosen, so a reader can tell what was measured on what
without having the rasters.

USAGE
-----
    import os, sys
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from paths import ROOT, SRC, DEM_ROOT, LAS_ROOT, ensure
    sys.path.insert(0, SRC)

`ensure()` checks the data roots exist and raises with the variable to set if
they do not, so a misconfigured run stops at the top with something actionable
rather than failing later on a missing file.
"""
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))

ROOT = os.environ.get("REPLICALM_ROOT") or os.path.dirname(_HERE)
SRC = os.path.join(ROOT, "src")
BENCHMARKS = os.path.join(ROOT, "benchmarks")
RESULTS = os.path.join(BENCHMARKS, "results")
DOCS = os.path.join(ROOT, "docs")
FIGURES = os.path.join(DOCS, "figures")

# Working directories for intermediates: gigabytes of clipped clouds and test
# rasters, gitignored, regenerated by the harness. Kept beside the repo by
# default so a clone does not scatter them.
TESTS = os.environ.get("REPLICALM_WORK") or os.path.join(ROOT, "tests")
RENDER = os.path.join(ROOT, "render")

_DEFAULT_DATA = "D:" + os.sep if os.name == "nt" else "/data"
DATA = os.environ.get("REPLICALM_DATA") or _DEFAULT_DATA

DEM_ROOT = os.environ.get("REPLICALM_DEM_ROOT") or os.path.join(
    DATA, "_Archive_EdgeFixed")
LAS_ROOT = os.environ.get("REPLICALM_LAS_ROOT") or os.path.join(
    DATA, "GLiHT_LAS_orig")

# Tools the pipeline can call but does not require. Overridable because their
# install location is a property of the machine, not of the method.
#
# PDAL_PYTHON is the interpreter that carries PDAL. On this machine that is
# the one shipped with ArcGIS Pro. The conda `replicalm` environment has
# PDAL too, but its BLAS is broken -- see ensure_blas below -- so it is not
# the default. ARCGIS_PYTHON is kept as the old name so existing callers
# keep working.
PDAL_PYTHON = os.environ.get(
    "REPLICALM_PDAL_PYTHON",
    r"C:\Program Files\ArcGIS\Pro\bin\Python\envs\arcgispro-py3\python.exe")
ARCGIS_PYTHON = PDAL_PYTHON
CLOUDCOMPARE = os.environ.get(
    "REPLICALM_CLOUDCOMPARE",
    r"C:\Program Files\CloudCompare\CloudCompare.exe")

_TOKENS = {"${ROOT}": ROOT, "${DATA}": DATA,
           "${DEM_ROOT}": DEM_ROOT, "${LAS_ROOT}": LAS_ROOT}


def expand(path):
    """Resolve a recorded path containing ${LAS_ROOT} and friends.

    Result files store roots as tokens rather than drive letters, so a result
    recorded on one machine names the same tile on another.
    """
    s = str(path)
    for token, value in _TOKENS.items():
        s = s.replace(token, value)
    return s


def tokenise(path):
    """The inverse: replace a known root with its token, for recording."""
    s = str(path)
    # longest first, so DEM_ROOT wins over the DATA prefix it contains
    for token, value in sorted(_TOKENS.items(), key=lambda kv: -len(kv[1])):
        if value and s.lower().startswith(value.lower()):
            return token + s[len(value):]
    return s


def ensure_blas():
    """Stop with an actionable message if this interpreter's BLAS is broken.

    The conda `replicalm` environment on this machine has a LAPACK/BLAS that
    aborts the process on any matmul or lstsq: Windows exception 0xc06d007f,
    exit 127, no traceback, and buffered stdout lost with it. A script that hits
    it appears to stop partway through for no reason, which cost an hour once.

    It cannot be tested in process, because the test is the crash. So the probe
    runs in a subprocess of this same interpreter, and costs about a third of a
    second.
    """
    import subprocess
    probe = "import numpy as np; np.ones((3, 3)) @ np.ones((3, 3))"
    try:
        r = subprocess.run([sys.executable, "-c", probe],
                           capture_output=True, timeout=120)
    except Exception:
        return True                      # cannot probe; do not block the run
    if r.returncode == 0:
        return True
    raise SystemExit(
        "Replicalm: this interpreter's BLAS is broken -- a 3x3 matmul aborts it "
        "(exit %d).\n  running  : %s\n  use      : %s\n\n"
        "Override with REPLICALM_PDAL_PYTHON."
        % (r.returncode, sys.executable, PDAL_PYTHON))


def ensure(*roots):
    """Check the data roots exist, naming the variable to set if they do not."""
    hint = {DEM_ROOT: "REPLICALM_DEM_ROOT", LAS_ROOT: "REPLICALM_LAS_ROOT",
            DATA: "REPLICALM_DATA", ROOT: "REPLICALM_ROOT"}
    missing = [r for r in (roots or (DEM_ROOT, LAS_ROOT)) if not os.path.isdir(r)]
    if missing:
        raise SystemExit(
            "Replicalm: these paths do not exist:\n  %s\n\n"
            "Set %s, or point REPLICALM_DATA at the directory holding\n"
            "_Archive_EdgeFixed and GLiHT_LAS_orig."
            % ("\n  ".join(missing),
               " / ".join(sorted({hint.get(r, "REPLICALM_DATA") for r in missing}))))
    return True


def describe():
    print("Replicalm paths")
    print("-" * 46)
    for name in ("ROOT", "SRC", "BENCHMARKS", "RESULTS", "TESTS",
                 "DATA", "DEM_ROOT", "LAS_ROOT", "PDAL_PYTHON"):
        value = globals()[name]
        mark = "" if os.path.exists(value) else "   (missing)"
        print("  %-11s %s%s" % (name, value, mark))


if __name__ == "__main__":
    describe()
